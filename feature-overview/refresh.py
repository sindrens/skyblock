#!/usr/bin/env python3
"""Regenerates INDEX.md, GRAPH.md, ORDER.md from features/*.md, LEDGER.md and rounds/.
Usage: python3 feature-overview/refresh.py [--summary]
Review state: Locked/Built come from the card status; Reviewing = a rounds/<ID>/ folder exists; else Todo."""
import re, glob, os, sys, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
FEAT = os.path.join(ROOT, 'features')
key = lambda x: (x[0], int(x[1:]))
ids = sorted([os.path.basename(f)[:-3] for f in glob.glob(FEAT + '/[A-I][0-9]*.md')], key=key)
txt = {i: open(f'{FEAT}/{i}.md').read() for i in ids}
head = {i: txt[i].split('\n')[0] for i in ids}
title = {i: head[i].split('·')[0].strip('# ').strip() for i in ids}
def hv(i, k, d='?'):
    m = re.search(k + r': ([\w ]+?)(?: ·|$)', head[i]); return m.group(1).strip() if m else d
status = {i: hv(i, 'status') for i in ids}; version = {i: hv(i, 'version') for i in ids}
pat = re.compile(r'\b([A-I][0-9]{1,2})\b'); idset = set(ids)
out = {}; inc = collections.Counter()
for i in ids:
    m = re.search(r'## Connections(.*?)(\n## |\Z)', txt[i], re.S)
    refs = ((set(pat.findall(m.group(1))) if m else set()) & idset) - {i}
    out[i] = refs
    for r in refs: inc[r] += 1
led = open(HERE + '/LEDGER.md').read().split('\n') if os.path.exists(HERE + '/LEDGER.md') else []
acc = collections.Counter(); rej = collections.Counter()
for l in led:
    m = re.match(r'\s*([A-I][0-9]+)-R\d+-\d+\s*\|\s*(accepted|rejected)', l)
    if m: (acc if m.group(2) == 'accepted' else rej)[m.group(1)] += 1
rip = collections.Counter()
if os.path.exists(HERE + '/RIPPLES.md'):
    for l in open(HERE + '/RIPPLES.md'):
        m = re.match(r'- \[ \] .*?\bto ([A-I][0-9]+)\b', l)
        if m: rip[m.group(1)] += 1
def rounds(i):
    return len(glob.glob(f'{HERE}/rounds/{i}/round-*.md'))
def state(i):
    if status[i] == 'Locked': return 'Locked'
    if status[i] == 'Built': return 'Built (verify)' if rounds(i) == 0 else 'Built (reviewed)'
    return 'Reviewing' if rounds(i) else 'Todo'
FIRST = ['C1','B17','C4','C14','B14','B13','E1','E3','E2','E4','E5','F5','F2','F1','I5',
         'D2','D1','D5','D6','D7','D3','D4','E10','E12','E13','E14',
         'C6','C7','C10','C11','C12','C13','H7','A3','A2','A4','A1']
rest = sorted([i for i in ids if i not in FIRST and status[i] != 'Built'], key=lambda i: (-inc[i], key(i)))
built = [i for i in ids if status[i] == 'Built' and i not in FIRST]
order = [i for i in FIRST if i in idset] + rest + built
MOD = {}
if os.path.exists(HERE + '/CODE-MAP.md'):
    for l in open(HERE + '/CODE-MAP.md'):
        m = re.match(r'\|\s*([A-I][0-9]+)\s*\|[^|]*\|\s*([^|]*)\|', l)
        if m: MOD[m.group(1)] = m.group(2).strip()
if '--summary' in sys.argv:
    c = collections.Counter(state(i) for i in ids); print(dict(c))
    nxt = [i for i in order if state(i) in ('Todo', 'Reviewing')][:5]
    print('next up:', ', '.join(f'{i} {title[i]} [{state(i)}]' for i in nxt)); sys.exit()
with open(HERE + '/INDEX.md', 'w') as f:
    f.write('# Feature review index (generated by refresh.py, do not edit by hand)\n\n')
    c = collections.Counter(state(i) for i in ids)
    f.write('Totals: ' + ', '.join(f'{k} {v}' for k, v in sorted(c.items())) + '\n\n')
    f.write('| # | Feature | Card status | Ver | Review state | Rounds | Accepted | Rejected | Open ripples | In-links | Code | Order |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n')
    for i in ids:
        f.write(f'| {i} | {title[i]} | {status[i]} | {version[i]} | {state(i)} | {rounds(i)} | {acc[i]} | {rej[i]} | {rip[i]} | {inc[i]} | {MOD.get(i, "")} | {order.index(i)+1} |\n')
with open(HERE + '/GRAPH.md', 'w') as f:
    f.write('# Card graph (generated from each card\'s Connections section)\n\nLoad "links to" and "linked from" cards when reviewing a feature.\n\n| Card | Links to | Linked from |\n|---|---|---|\n')
    for i in ids:
        back = sorted([j for j in ids if i in out[j]], key=key)
        f.write(f'| {i} {title[i]} | {" ".join(sorted(out[i], key=key))} | {" ".join(back)} |\n')
with open(HERE + '/ORDER.md', 'w') as f:
    f.write('# Review order (generated; the first block is fixed in refresh.py FIRST, the rest follows by in-links)\n\n')
    f.write('Biggest and most connected first: a wrong decision in a card with many in-links spreads to all of them.\n\n| Order | Feature | In-links | State |\n|---|---|---|---|\n')
    for n, i in enumerate(order, 1):
        f.write(f'| {n} | {i} {title[i]} | {inc[i]} | {state(i)} |\n')
print('refreshed:', len(ids), 'cards')
