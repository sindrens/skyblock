package net.skybornmc.skyblock.common.pack;

import org.bukkit.configuration.ConfigurationSection;
import org.bukkit.configuration.InvalidConfigurationException;
import org.bukkit.configuration.file.YamlConfiguration;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;

/**
 * Everything the plugin knows about the pack, read from {@code pack/pack-ids.yml} in the plugin jar. That file is
 * GENERATED by {@code tools/build_pack.py} together with the zips, so ids in code and art in the pack never drift
 * (unit tests check every id the code uses against it).
 */
public record PackIds(
        String version,
        Map<String, Zip> zips,
        Menu menu,
        Set<String> icons,
        Map<String, String> glyphs,
        Map<Integer, String> spaces,
        String letterGap,
        Map<String, Badge> badges,
        Set<String> sounds,
        Map<String, Crate> crates) {

    public static final String RESOURCE = "pack/pack-ids.yml";

    /** One built zip ({@code safe} or {@code shine}). */
    public record Zip(String file, String sha1) {
    }

    /** One menu background glyph. */
    public record Background(String id, String glyph, int rows) {
    }

    /** Menu title metrics and backgrounds; {@code classes} maps {@code module/SimpleClassName} to a background id. */
    public record Menu(int ascent, int titleOffset, String titleColor, int width,
                       Map<String, Background> backgrounds, Map<String, String> classes) {

        /** The background for a menu class, by its module and simple class name. */
        public Optional<Background> backgroundFor(String module, String simpleClassName) {
            return Optional.ofNullable(classes.get(module + "/" + simpleClassName)).map(backgrounds::get);
        }
    }

    /**
     * The badge look for one LuckPerms group id. {@code colors} has one entry, or several for a gradient.
     * {@code font} is the shine font for shining ranks; the still and large variants are derived by name.
     */
    public record Badge(String group, String font, List<String> colors, String capColor, boolean shine,
                        String family, String bedrock, String capLeft, String capRight) {
    }

    /** A crate chest model, its split body/lid models and the lid hinge (model units, 1/16 block). */
    public record Crate(String id, String model, String body, String lid, double hingeY, double hingeZ) {
    }

    /** Loads the bundled file from the given class loader (the plugin's). */
    public static PackIds load(ClassLoader loader) throws IOException {
        try (InputStream in = loader.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                throw new IOException(RESOURCE + " is missing from the jar (run python3 tools/build_pack.py)");
            }
            return parse(new InputStreamReader(in, StandardCharsets.UTF_8));
        }
    }

    public static PackIds parse(Reader reader) throws IOException {
        YamlConfiguration y = new YamlConfiguration();
        try {
            y.load(reader);
        } catch (InvalidConfigurationException e) {
            throw new IOException("bad " + RESOURCE + ": " + e.getMessage(), e);
        }
        Map<String, Zip> zips = new LinkedHashMap<>();
        section(y, "zips").forEach((k, s) -> zips.put(k, new Zip(s.getString("file"), s.getString("sha1"))));

        Map<String, Background> bgs = new LinkedHashMap<>();
        section(y, "menu.backgrounds").forEach((k, s) -> bgs.put(k, new Background(k, s.getString("char"), s.getInt("rows"))));
        Map<String, String> classes = strings(y, "menu.classes");
        Menu menu = new Menu(y.getInt("menu.ascent"), y.getInt("menu.title-offset"), y.getString("menu.title-color"),
                y.getInt("menu.width"), bgs, classes);

        Map<Integer, String> spaces = new LinkedHashMap<>();
        strings(y, "space").forEach((k, v) -> {
            if (!k.equals("font")) {
                spaces.put(Integer.parseInt(k), v);
            }
        });

        Map<String, Badge> badges = new LinkedHashMap<>();
        section(y, "badges.ranks").forEach((k, s) -> {
            List<String> caps = s.getStringList("caps");
            badges.put(k, new Badge(k, s.getString("font"), List.of(s.getString("color", "#FFFFFF").split(",")),
                    s.getString("cap-color"), s.getBoolean("shine"), s.getString("family"), s.getString("bedrock"),
                    caps.size() > 0 ? caps.get(0) : "", caps.size() > 1 ? caps.get(1) : ""));
        });

        Map<String, Crate> crates = new LinkedHashMap<>();
        section(y, "crates").forEach((k, s) -> crates.put(k, new Crate(k, s.getString("model"), s.getString("body"),
                s.getString("lid"), s.getDouble("hinge-y"), s.getDouble("hinge-z"))));

        return new PackIds(y.getString("version"), zips, menu, new LinkedHashSet<>(y.getStringList("icons")),
                strings(y, "glyphs"), spaces, y.getString("badges.letter-gap", ""), badges,
                new LinkedHashSet<>(y.getStringList("sounds")), crates);
    }

    /** The badge for a group id, or the plain default (Ashborn) look when the group has no style. */
    public Badge badge(String group) {
        Badge b = group == null ? null : badges.get(group.toLowerCase(java.util.Locale.ROOT));
        return b != null ? b : badges.get("default");
    }

    /**
     * Characters from the {@code phoenix:space} font that add up to {@code pixels} (negative moves left). Uses the
     * power-of-two advances, so any value in -511..511 is exact.
     */
    public String space(int pixels) {
        StringBuilder out = new StringBuilder();
        int sign = pixels < 0 ? -1 : 1;
        int left = Math.abs(pixels);
        for (int bit = 256; bit >= 1; bit >>= 1) {
            if (left >= bit) {
                String c = spaces.get(sign * bit);
                if (c == null) {
                    throw new IllegalStateException("no space glyph for " + sign * bit);
                }
                out.append(c);
                left -= bit;
            }
        }
        return out.toString();
    }

    private static Map<String, ConfigurationSection> section(ConfigurationSection root, String path) {
        Map<String, ConfigurationSection> out = new LinkedHashMap<>();
        ConfigurationSection s = root.getConfigurationSection(path);
        if (s != null) {
            for (String k : s.getKeys(false)) {
                ConfigurationSection c = s.getConfigurationSection(k);
                if (c != null) {
                    out.put(k, c);
                }
            }
        }
        return out;
    }

    private static Map<String, String> strings(ConfigurationSection root, String path) {
        Map<String, String> out = new LinkedHashMap<>();
        ConfigurationSection s = root.getConfigurationSection(path);
        if (s != null) {
            for (String k : s.getKeys(false)) {
                out.put(k, s.getString(k));
            }
        }
        return out;
    }
}
