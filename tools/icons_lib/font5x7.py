def glyph(font, ch):
    """Rows of ``ch`` in ``font`` (capitals for letters); a blank glyph for an unknown character."""
    g = font.get(ch.upper())
    if g is None:
        width = len(next(iter(font.values()))[0])
        height = len(next(iter(font.values())))
        return [' ' * width] * height
    return g
